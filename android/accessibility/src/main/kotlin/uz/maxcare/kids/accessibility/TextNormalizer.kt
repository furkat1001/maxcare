package uz.maxcare.kids.accessibility

import java.util.Locale

/**
 * Приводит текст к канону для сравнения со словарём, снимая типичные приёмы обхода:
 * регистр, замены букв цифрами/символами (leet), смешение латиницы и кириллицы (гомоглифы),
 * разделители и узбекские апострофы, повторы букв.
 *
 * Одна и та же функция применяется и к вводу, и к словам словаря — канон может выглядеть
 * непривычно, но важна только его детерминированность: тогда «пoрно» с латинской «o» и
 * «порно» сводятся к одному виду.
 *
 * Известный пробел (доработка позже): leet-замены дают латинские буквы, поэтому кириллические
 * слова, записанные цифрами, нормализуются не полностью; полная узбекско-русская нормализация —
 * предмет отдельной работы (см. docs/research.md, ИИ-модели).
 */
object TextNormalizer {

    // Замены букв цифрами/символами (leet) → буквы: 0→o, 1→i, 3→e, 4→a, 5→s, 7→t, @→a, $→s.
    private val leet = "013457@$".zip("oieastas").toMap()

    // Латинские буквы → визуально совпадающие кириллические (a→а, c→с, e→е, o→о, p→р, x→х,
    // y→у, k→к, m→м). Сворачиваем смешение алфавитов к одному виду; важна лишь одинаковость
    // преобразования для ввода и для словаря.
    private val homoglyphs = "aceopxykm".zip("асеорхукм").toMap()

    fun normalize(input: String?): String {
        if (input.isNullOrBlank()) return ""

        val sb = StringBuilder(input.length)
        var previous = '\u0000'
        for (raw in input.lowercase(Locale.ROOT)) {
            val deLeet = leet[raw] ?: raw
            val folded = homoglyphs[deLeet] ?: deLeet
            // Оставляем только буквы (снимаем пробелы, пунктуацию, апострофы, прочие цифры)
            // и схлопываем повторы: «пооорн» → «порн».
            if (folded.isLetter() && folded != previous) {
                sb.append(folded)
                previous = folded
            }
        }
        return sb.toString()
    }
}
